package com.bank.dao;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.sql.Statement;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;

public final class DatabaseManager {
    private static volatile String jdbcUrl = System.getProperty(
            "bank.db.url", "jdbc:h2:file:./data/bankdb;DB_CLOSE_ON_EXIT=FALSE");

    private DatabaseManager() { }

    public static Connection getConnection() throws SQLException {
        createDatabaseDirectoryIfNeeded();
        return DriverManager.getConnection(jdbcUrl, "sa", "");
    }

    private static void createDatabaseDirectoryIfNeeded() throws SQLException {
        String prefix = "jdbc:h2:file:";
        if (!jdbcUrl.startsWith(prefix)) return;
        String filePath = jdbcUrl.substring(prefix.length()).split(";", 2)[0];
        Path parent = Path.of(filePath).toAbsolutePath().getParent();
        if (parent == null) return;
        try { Files.createDirectories(parent); }
        catch (IOException ex) { throw new SQLException("Could not create the database directory.", ex); }
    }

    /** Allows tests to select a separate database before initializing the schema. */
    public static void useJdbcUrl(String url) {
        if (url == null || url.isBlank()) throw new IllegalArgumentException("JDBC URL is required.");
        jdbcUrl = url;
    }

    public static void initializeDatabase() {
        try (Connection connection = getConnection(); Statement statement = connection.createStatement()) {
            statement.execute("CREATE TABLE IF NOT EXISTS customers ("
                    + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "customer_type VARCHAR(20) NOT NULL, email VARCHAR(160) NOT NULL, address VARCHAR(250) NOT NULL, "
                    + "username VARCHAR(50) NOT NULL UNIQUE, password_hash VARCHAR(250) NOT NULL, "
                    + "first_name VARCHAR(80), surname VARCHAR(80), company_name VARCHAR(140), "
                    + "company_reg_no VARCHAR(80), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, "
                    + "CHECK (customer_type IN ('INDIVIDUAL','COMPANY'))) ");
            statement.execute("CREATE TABLE IF NOT EXISTS accounts ("
                    + "account_number VARCHAR(24) PRIMARY KEY, customer_id BIGINT NOT NULL, "
                    + "account_type VARCHAR(20) NOT NULL, branch VARCHAR(100) NOT NULL, "
                    + "balance DECIMAL(15,2) NOT NULL CHECK (balance >= 0), employment_details VARCHAR(200), "
                    + "opened_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, "
                    + "CHECK (account_type IN ('SAVINGS','INVESTMENT','CHEQUE')), "
                    + "FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE CASCADE)");
            statement.execute("CREATE TABLE IF NOT EXISTS transactions ("
                    + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, account_number VARCHAR(24) NOT NULL, "
                    + "transaction_type VARCHAR(20) NOT NULL, amount DECIMAL(15,2) NOT NULL, "
                    + "balance_after DECIMAL(15,2) NOT NULL, description VARCHAR(200), "
                    + "created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, "
                    + "FOREIGN KEY (account_number) REFERENCES accounts(account_number) ON DELETE CASCADE)");
            statement.execute("CREATE TABLE IF NOT EXISTS interest_payments ("
                    + "account_number VARCHAR(24) NOT NULL, payment_month DATE NOT NULL, "
                    + "PRIMARY KEY (account_number, payment_month), "
                    + "FOREIGN KEY (account_number) REFERENCES accounts(account_number) ON DELETE CASCADE)");
            seedTenCustomersAndAccounts(connection);
        } catch (SQLException ex) {
            throw new IllegalStateException("Could not initialize the banking database.", ex);
        }
    }

    public static void resetDatabase() {
        try (Connection connection = getConnection(); Statement statement = connection.createStatement()) {
            statement.execute("DROP ALL OBJECTS");
        } catch (SQLException ex) {
            throw new IllegalStateException("Could not reset the banking database.", ex);
        }
        initializeDatabase();
    }

    private static void seedTenCustomersAndAccounts(Connection connection) throws SQLException {
        String customerSql = "INSERT INTO customers (customer_type,email,address,username,password_hash,first_name,surname) "
                + "SELECT 'INDIVIDUAL',?,?,?,?,?,? WHERE NOT EXISTS (SELECT 1 FROM customers WHERE username=?)";
        try (PreparedStatement customer = connection.prepareStatement(customerSql)) {
            for (int i = 1; i <= 10; i++) {
                String username = "user" + i;
                customer.setString(1, username + "@example.test");
                customer.setString(2, "Gaborone, Botswana");
                customer.setString(3, username);
                customer.setString(4, PasswordEncoder.encode("pass" + i));
                customer.setString(5, "Customer");
                customer.setString(6, Integer.toString(i));
                customer.setString(7, username);
                customer.addBatch();
            }
            customer.executeBatch();
        }

        String accountSql = "INSERT INTO accounts (account_number,customer_id,account_type,branch,balance,employment_details) "
                + "SELECT ?,id,?,?,?,? FROM customers WHERE username=? "
                + "AND NOT EXISTS (SELECT 1 FROM accounts WHERE account_number=?)";
        try (PreparedStatement account = connection.prepareStatement(accountSql)) {
            for (int i = 1; i <= 10; i++) {
                String number = "ACC%03d".formatted(i);
                String type = i == 2 ? "INVESTMENT" : i == 10 ? "CHEQUE" : "SAVINGS";
                account.setString(1, number);
                account.setString(2, type);
                account.setString(3, "Gaborone Main");
                account.setBigDecimal(4, BigDecimal.valueOf(i == 2 ? 5_000 : 1_000));
                account.setString(5, i == 10 ? "Example employer, Gaborone" : null);
                account.setString(6, "user" + i);
                account.setString(7, number);
                account.addBatch();
            }
            account.executeBatch();
        }
    }
}
